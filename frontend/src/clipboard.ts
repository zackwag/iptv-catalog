/**
 * navigator.clipboard is only defined in secure contexts (HTTPS or
 * localhost) — on a plain-HTTP LAN address it's undefined, so calling
 * .writeText on it throws synchronously and the click handler aborts
 * silently. Fall back to the legacy execCommand approach in that case.
 */
export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // fall through to legacy method
    }
  }

  try {
    const textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.style.position = "fixed";
    textarea.style.opacity = "0";
    document.body.appendChild(textarea);
    textarea.focus();
    textarea.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(textarea);
    return ok;
  } catch {
    return false;
  }
}
